#!/bin/bash
#
# nvim-wez.sh — Open file(s) in Neovim inside WezTerm/Zellij
#
# WHAT
#   Smart launcher that opens its file arguments in nvim inside the focused
#   Zellij session when WezTerm is currently hosting one, falling back to the
#   existing bare-WezTerm nvim tab when no Zellij client can be resolved. Tab
#   title is derived from the arguments: bare → "NeoVim", one file → its
#   basename, many → "<first> +N".
#
# HOW
#   Zellij path: ask WezTerm for the active pane TTY, find the Zellij client
#   running there, resolve its session via ~/.config/zellij/scripts/lib, and
#   run `zellij --session <name> action new-tab -- nvim "$@"`.
#   Fallback path: point WEZTERM_UNIX_SOCKET at a running GUI socket, raise
#   the app via osascript, `wezterm cli spawn -- nvim "$@"`, capture the
#   spawned PANE_ID, and `wezterm cli set-tab-title --pane-id <id>`.
#
# WHERE IT'S USED
#   Invoked by the generated macOS Finder droplet at
#   ~/Applications/Open in NeoVim.app. The droplet surfaces in Finder's
#   right-click → Open With menu and accepts drag-and-drop, so this script
#   is the engine behind the "Open in nvim/WezTerm" macOS-native action.
#   The app is regenerated by
#   run_onchange_after_35-generate-open-in-neovim-app.sh.tmpl.
#
# PLATFORM
#   macOS-only: relies on `open -a`, AppleScript activation, and the
#   WezTerm GUI socket layout. Excluded from non-darwin targets via
#   .chezmoiignore.tmpl.

# 1. SET PATHS
export PATH="$HOME/.local/bin:/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin"

WEZTERM_BIN="${WEZTERM_BIN:-/opt/homebrew/bin/wezterm}"
NVIM_BIN="${NVIM_BIN:-/opt/homebrew/bin/nvim}"
ZELLIJ_BIN="${ZELLIJ_BIN:-/opt/homebrew/bin/zellij}"
JQ_BIN="${JQ_BIN:-/opt/homebrew/bin/jq}"
ZELLIJ_SESSION_LIB="${ZELLIJ_SESSION_LIB:-$HOME/.config/zellij/scripts/lib/zellij-session.sh}"

# 2. CALCULATE TAB TITLE
COUNT=$#
if [ "$COUNT" -eq 0 ]; then
  TAB_TITLE="NeoVim"
elif [ "$COUNT" -eq 1 ]; then
  TAB_TITLE=$(basename -- "$1")
else
  FIRST_BASE=$(basename -- "$1")
  OTHERS=$((COUNT - 1))
  TAB_TITLE="$FIRST_BASE +$OTHERS"
fi

# 3. CALCULATE WORKING DIRECTORY
CWD=""
if [ "$COUNT" -gt 0 ]; then
  FIRST_PATH="$1"
  if [ -d "$FIRST_PATH" ]; then
    FIRST_DIR="$FIRST_PATH"
  else
    FIRST_DIR=$(dirname -- "$FIRST_PATH")
  fi

  if [ -d "$FIRST_DIR" ]; then
    GIT_ROOT=$(git -C "$FIRST_DIR" rev-parse --show-toplevel 2>/dev/null) || GIT_ROOT=""
    CWD="${GIT_ROOT:-$FIRST_DIR}"
  fi
fi

WEZTERM_CWD_ARGS=()
ZELLIJ_CWD_ARGS=()
if [ -n "$CWD" ]; then
  WEZTERM_CWD_ARGS=(--cwd "$CWD")
  ZELLIJ_CWD_ARGS=(--cwd "$CWD")
fi

active_wezterm_pane() {
  [ -x "$WEZTERM_BIN" ] && [ -x "$JQ_BIN" ] || return 1
  "$WEZTERM_BIN" cli --no-auto-start list --format json 2>/dev/null \
    | "$JQ_BIN" -r '.[] | select(.is_active) | [.pane_id, .window_id, .tty_name] | @tsv' 2>/dev/null \
    | sed -n '1p'
}

active_zellij_session() {
  [ -x "$ZELLIJ_BIN" ] && [ -r "$ZELLIJ_SESSION_LIB" ] || return 1

  PANE_INFO=$(active_wezterm_pane) || return 1
  [ -n "$PANE_INFO" ] || return 1

  IFS="$(printf '\t')" read -r _ACTIVE_PANE _ACTIVE_WINDOW ACTIVE_TTY <<EOF
$PANE_INFO
EOF
  [ -n "$ACTIVE_TTY" ] || return 1

  CLIENT_PID=$(ps -t "${ACTIVE_TTY#/dev/}" -o pid=,comm= 2>/dev/null \
    | awk '$2 ~ /zellij/ {print $1; exit}')
  [ -n "$CLIENT_PID" ] || return 1

  # shellcheck source=/dev/null
  . "$ZELLIJ_SESSION_LIB"
  resolve_session "$CLIENT_PID" 2>/dev/null
}

open_in_active_zellij() {
  SESSION=$(active_zellij_session) || return 1
  [ -n "$SESSION" ] || return 1

  osascript -e 'tell application "WezTerm" to activate' >/dev/null 2>&1 || true
  "$ZELLIJ_BIN" --session "$SESSION" action new-tab \
    "${ZELLIJ_CWD_ARGS[@]}" --name "$TAB_TITLE" --close-on-exit -- "$NVIM_BIN" "$@"
}

open_in_wezterm() {
  # FIND ACTIVE PROCESS & SOCKET
  W_PID=$(pgrep -x "wezterm-gui" | sed -n '1p')
  [ -n "$W_PID" ] || W_PID=$(pgrep -x "wezterm" | sed -n '1p')

  if [ -z "$W_PID" ]; then
    # CASE: COLD START
    open -a WezTerm --args start "${WEZTERM_CWD_ARGS[@]}" -- "$NVIM_BIN" "$@"

    # Wait for socket and apply title to the active tab of the new PID
    sleep 1.2
    NEW_PID=$(pgrep -x "wezterm-gui" | sed -n '1p')
    [ -n "$NEW_PID" ] || NEW_PID=$(pgrep -x "wezterm" | sed -n '1p')
    if [ -n "$NEW_PID" ]; then
      export WEZTERM_UNIX_SOCKET="$HOME/.local/share/wezterm/gui-sock-$NEW_PID"
      "$WEZTERM_BIN" cli set-tab-title "$TAB_TITLE" 2>/dev/null
    fi
  else
    # CASE: ALREADY RUNNING
    export WEZTERM_UNIX_SOCKET="$HOME/.local/share/wezterm/gui-sock-$W_PID"

    # Bring to front
    osascript -e 'tell application "WezTerm" to activate' >/dev/null 2>&1 || true

    # SPAWN AND CAPTURE PANE ID
    PANE_ID=$("$WEZTERM_BIN" cli spawn "${WEZTERM_CWD_ARGS[@]}" -- "$NVIM_BIN" "$@" 2>/dev/null)

    if [ -z "$PANE_ID" ]; then
      sleep 0.5
      PANE_ID=$("$WEZTERM_BIN" cli spawn "${WEZTERM_CWD_ARGS[@]}" -- "$NVIM_BIN" "$@")
    fi

    # SET TITLE VIA PANE CONTEXT
    # Instead of --tab-id, we use --pane-id.
    # WezTerm will resolve the tab that contains this pane.
    if [ -n "$PANE_ID" ]; then
      "$WEZTERM_BIN" cli set-tab-title "$TAB_TITLE" --pane-id "$PANE_ID"
    fi
  fi
}

open_in_active_zellij "$@" || open_in_wezterm "$@"
