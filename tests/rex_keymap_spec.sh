    End
  End

  Describe 'direct chords'
    It 'binds the three pickers to their Cmd chords'
      pickers() {
        line 'rex.bind("cmd+shift+s", "ql_workspace")'
        line 'rex.bind("cmd+shift+t", "ql_tab")'
        line 'rex.bind("cmd+shift+p", "ql_pane")'
      }
      When call pickers
      The lines of output should equal 3
    End

    It 'maps Cmd+0 to the tenth tab'
      When call line 'rex.bind("cmd+0", "client.tab.goto", { index = 10 })'
      The output should be present
    End

    It 'emits nothing for a refused chord'
      refused() { grep -c -E '^rex\.bind\("cmd\+shift\+(f|v)",' "$RK_LUA" || true; }
      When call refused
      The output should equal "0"
    End
  End

  # Ctrl+h/j/k/l and Ctrl+arrows: one motion across Rex panes and nvim
  # splits. Hand-written in the template header, like their tmux twins.
  Describe 'context keys'
    It 'binds the eight navigation keys to functions, each to its direction'
      nav() {
        local k
        for k in 'ctrl+h"] = "left"' 'ctrl+j"] = "down"' 'ctrl+k"] = "up"' 'ctrl+l"] = "right"' \
                 'ctrl+left"] = "left"' 'ctrl+down"] = "down"' 'ctrl+up"] = "up"' 'ctrl+right"] = "right"'; do
          grep -qF "[\"$k" "$RK_LUA" || print -r -- "missing: $k"
        done
      }
      When call nav
      The output should equal ""
    End

    It 'binds the eight resize keys'
      resize() { grep -c -E '^  \["ctrl\+shift\+(h|j|k|l|left|down|up|right)"\] = "(left|down|up|right)"' "$RK_LUA" || true; }
      When call resize
      # two lines of four
      The output should equal "2"
    End

    # The pass-through rule is a restatement of the tmux probe's regex. If
    # one grows a name the other must too, so the spec reads the regex out of
    # keymap-base.conf and checks the Lua comment still quotes it.
    It 'quotes the same vim-family rule as the tmux probe'
      same_rule() {
        grep -qF 'g?(view|l?n?vim?x?)(diff)?' home/dot_config/tmux/keymap-base.conf.tmpl || { print -r -- "tmux regex moved"; return; }
        grep -qF 'g?(view|l?n?vim?x?)(diff)?' "$RK_LUA" || print -r -- "lua comment no longer quotes it"
        grep -qF '|fzf)$' home/dot_config/tmux/keymap-base.conf.tmpl || print -r -- "tmux no longer passes fzf"
      }
      When call same_rule
      The output should equal ""
    End

    Describe 'the probe, run by Rex'
      rex_missing() { ! command -v rex >/dev/null 2>&1; }
      Skip if 'rex is not installed' rex_missing

      rx() { command rex --autostart=false -S "$CK_SERVER" "$@"; }
      start_server() {
        CK_STATE=$(mktemp -d)
        CK_SOCK="/tmp/ckrx-$$.sock"
        CK_SERVER="unix://$CK_SOCK"
        : > "$CK_STATE/init.lua"
        command rex server run --listen "$CK_SERVER" --state-dir "$CK_STATE/state" \
          --config "$CK_STATE/init.lua" --restore=false >"$CK_STATE/server.log" 2>&1 &
        CK_PID=$!
        local i
        for i in {1..50}; do rx whoami >/dev/null 2>&1 && break; sleep 0.1; done
        # The helpers exactly as shipped, cut out of the rendered config, with
        # a tail that reports what they decide for the pane the script runs
        # against.
        {
          awk '/^local TERMINAL = /,/^-- Navigation is a FUNCTION bind/' "$RK_LUA" | sed '$d'
          # A key function gets the focused pane in ctx.block_id; a script
          # has no focused pane, so the spec names one.
          print -r -- 'local ctx = { block_id = rex.args.block }'
          print -r -- 'return { nav = pane_runs(ctx, is_vim_or_fzf), resize = pane_runs(ctx, is_vim),'
          print -r -- '  names = { is_vim("nvim"), is_vim("vim"), is_vim("vi"), is_vim("view"), is_vim("gvimdiff"), is_vim("lnvim"),'
          print -r -- '            is_vim("zsh"), is_vim("gzip"), is_vim("fzf"), is_vim_or_fzf("fzf"), is_vim("vimtutor") } }'
        } >"$CK_STATE/probe.lua"
        # Stand-ins named like the real programs: the probe reads comm.
        mkdir -p "$CK_STATE/bin"
        ln -s /bin/sleep "$CK_STATE/bin/nvim"
        ln -s /bin/sleep "$CK_STATE/bin/fzf"
      }
      stop_server() {
        rx server stop >/dev/null 2>&1
        kill "$CK_PID" 2>/dev/null
        rm -rf "$CK_STATE" "$CK_SOCK"
      }
      BeforeAll 'start_server'
      AfterAll 'stop_server'

      # probe <command...> — start a pane running that command and ask the
      # shipped helpers about it.
      probe() {
        local sid bid
        sid=$(rx new "p-$RANDOM" --shell none --json -- "$@" | jq -r '.session_id')
        bid=$(rx block ls -s "$sid" --json | jq -r '.blocks[0].block_id')
        sleep 0.3
        rx do -s "$sid" "$CK_STATE/probe.lua" "block=$bid" | jq -c "$PROBE_FILTER"
      }

      It 'moves focus from a pane running a plain program'
        PROBE_FILTER='{nav, resize}'
        When call probe /bin/sleep 30
        The output should equal '{"nav":false,"resize":false}'
      End

      It 'passes both key families to a pane running nvim'
        PROBE_FILTER='{nav, resize}'
        When call probe "$CK_STATE/bin/nvim" 30
        The output should equal '{"nav":true,"resize":true}'
      End

      It 'passes navigation, but not resize, to fzf'
        PROBE_FILTER='{nav, resize}'
        When call probe "$CK_STATE/bin/fzf" 30
        The output should equal '{"nav":true,"resize":false}'
      End

      # The case Rex's own foreground report gets wrong: the program runs
      # inside the SHELL's process group, as fzf does from a zsh widget.
      It 'sees a program started inside the shell'"'"'s own process group'
        PROBE_FILTER='{nav}'
        When call probe /bin/zsh -fc "$CK_STATE/bin/fzf 30; true"
        The output should equal '{"nav":true}'
      End

      It 'recognises the vim family and nothing near it'
        PROBE_FILTER='.names'
        When call probe /bin/sleep 30
        The output should equal '[true,true,true,true,true,true,false,false,false,true,false]'
      End
    End

    # Resize moves a border on the server (session.resize_pane), not through
    # the client's pane.resize: nvim has to reach it from the CLI, and a
    # shell pane and an nvim pane must resize the same way.
    It 'resizes on the server, through one function'
      shape() {
        grep -c -F 'rex.client.queue("pane.resize"' "$RK_LUA" || true
        grep -c -E '^      resize_by\(ctx\.session_id, ctx\.block_id, args\.direction, RESIZE_STEP\)$' "$RK_LUA" || true
        grep -c -E '^    return resize_by\(ctx\.session_id, ctx\.block_id, args\.direction, args\.cells\)$' "$RK_LUA" || true
      }
      When call shape
      The line 1 of output should equal "0"
      The line 2 of output should equal "1"
      The line 3 of output should equal "1"
    End

    Describe 'the resize action, run by Rex'
      rex_missing() { ! command -v rex >/dev/null 2>&1; }
      Skip if 'rex is not installed' rex_missing

      rx() { command rex --autostart=false -S "$RZ_SERVER" "$@"; }
      # The layout  A | ((B | D) / C)  — a border on every side of B.
      start_server() {
        RZ_STATE=$(mktemp -d)
        RZ_SOCK="/tmp/rzrx-$$.sock"
        RZ_SERVER="unix://$RZ_SOCK"
        # The action exactly as shipped, cut out of the rendered config.
        {
          print -r -- 'local TERMINAL = "com.superlogical.terminal"'
          awk '/^local RESIZE_STEP = /,/^-- The key side is an ACTION/' "$RK_LUA" | sed '$d'
        } >"$RZ_STATE/init.lua"
        command rex server run --listen "$RZ_SERVER" --state-dir "$RZ_STATE/state" \
          --config "$RZ_STATE/init.lua" --restore=false >"$RZ_STATE/server.log" 2>&1 &
        RZ_PID=$!
        local i
        for i in {1..50}; do rx whoami >/dev/null 2>&1 && break; sleep 0.1; done
      }
      stop_server() {
        rx server stop >/dev/null 2>&1
        kill "$RZ_PID" 2>/dev/null
        rm -rf "$RZ_STATE" "$RZ_SOCK"
      }
      BeforeAll 'start_server'
      AfterAll 'stop_server'

      # A fresh four-pane session per example: RZ_SID, RZ_A … RZ_D.
      layout() {
        RZ_SID=$(rx new "z-$RANDOM" --shell none --json -- /bin/sleep 60 | jq -r '.session_id')
        RZ_A=$(rx block ls -s "$RZ_SID" --json | jq -r '.blocks[0].block_id')
        RZ_B=$(rx run -s "$RZ_SID" -b "$RZ_A" --split right --shell none --json -- /bin/sleep 60 | jq -r '.block_ids[0]')
        RZ_C=$(rx run -s "$RZ_SID" -b "$RZ_B" --split below --shell none --json -- /bin/sleep 60 | jq -r '.block_ids[0]')
        RZ_D=$(rx run -s "$RZ_SID" -b "$RZ_B" --split right --shell none --json -- /bin/sleep 60 | jq -r '.block_ids[0]')
      }
      # ratios — the three splits, outermost first: A|rest, top/C, B|D.
      ratios() {
        rx api call -s "$RZ_SID" session.view | jq -c '
          .windows[0].layers[0].layout.split as $h
          | [$h.ratio, $h.after.split.ratio, $h.after.split.before.split.ratio]
          | map(. * 10000 | round / 10000)'
      }
      # resize <pane> <direction> <cells> — then print the ratios.
      resize() {
        layout
        local pane=${(P)${:-RZ_$1}}
        rx do pane_resize_by -b "$pane" "direction=$2" "cells=$3" -s "$RZ_SID" >/dev/null
        ratios
      }

      # No client shows these panes, so each reports 80x24 and the window is
      # taken to be (80 / the pane's share) wide: 160 columns seen from A.
      It 'moves the border on the pressed side'
        When call resize A right 4
        The output should equal '[0.525,0.5,0.5]'
      End

      # B covers a quarter of the width, so the same 80 columns read as a
      # 320-column window here: 4 cells are half the ratio they were from A.
      It 'moves the same border back from the other pane'
        When call resize B left 4
        The output should equal '[0.4875,0.5,0.5]'
      End

      It 'moves the border on the other side for a pane at the far edge'
        When call resize D right 4
        The output should equal '[0.5,0.5,0.525]'
      End

      It 'picks the nearest border on that side in a nested layout'
        When call resize B right 4
        The output should equal '[0.5,0.5,0.525]'
      End

      It 'moves a horizontal border'
        When call resize B down 2
        The output should equal '[0.5,0.5417,0.5]'
      End

      It 'does nothing when there is no border on that axis'
        When call resize A down 2
        The output should equal '[0.5,0.5,0.5]'
      End

      It 'reports whether it moved anything'
        report() { layout; rx do pane_resize_by -b "$RZ_A" "direction=$1" cells=2 -s "$RZ_SID"; }
        When call report down
        The output should equal 'false'
      End
    End
  End

