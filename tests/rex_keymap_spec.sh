# Tests for the GENERATED Rex config — home/dot_config/rex/init.lua.tmpl,
# rendered from home/.chezmoidata/keymap.yaml.
#
# keymap.yaml is the single source for three consumers now: the tmux key
# tables, the which-key panel, and Rex's bindings. Each leader-table entry
# carries a `rex:` answer beside its tmux `cmd:`; `keymap.direct` lists the
# Cmd chords. What is pinned here:
#
#   * every entry HAS an answer (an action, {action, args}, true for a mode
#     switch, or false with a reason) — a new tmux binding cannot be added
#     without deciding what it means on Rex;
#   * the three mode-stack behaviours the YAML encodes come out as the three
#     binding shapes, each through an action of the entry's own, titled for
#     Rex's key-hint overlay (switch → km_stay entering the mode, sticky →
#     km_stay repeating the action, otherwise → km_leave, which leaves the
#     mode first);
#   * the file Rex would actually load is valid, and names only actions that
#     exist.
Describe 'generated Rex config'
  setup_all() {
    RK_TMP=$(mktemp -d)
    chezmoi -S "$SHELLSPEC_PROJECT_ROOT" execute-template <home/dot_config/rex/init.lua.tmpl >"$RK_TMP/init.lua" 2>"$RK_TMP/render.err"
    RK_RC=$?
    RK_LUA="$RK_TMP/init.lua"
  }
  cleanup_all() { [ -n "$RK_TMP" ] && rm -rf "$RK_TMP"; }
  BeforeAll setup_all
  AfterAll cleanup_all

  line() { grep -F -- "$1" "$RK_LUA"; }
  tables_json() { yq -o=json '.keymap.tables' home/.chezmoidata/keymap.yaml; }

  It 'renders'
    rendered() { print -r -- "$RK_RC"; cat "$RK_TMP/render.err"; }
    When call rendered
    The output should equal "0"
  End

  It 'carries the marker the backup script looks for'
    When call line 'GENERATED by chezmoi'
    The status should be success
    The output should be present
  End

  Describe 'keymap.yaml answers'
    It 'has a rex: answer on every leader-table entry'
      missing() {
        tables_json | jq -r '
          to_entries[] | select(.key | IN("scroll", "copy", "search") | not)
          | .key as $t | .value.entries[] | select(has("rex") | not) | "\($t): \(.desc)"'
      }
      When call missing
      The output should equal ""
    End

    It 'leaves the native-replaced tables without answers, on purpose'
      # scroll/copy/search are not generated; an answer there would be dead
      # data that looks like a binding.
      stray() {
        tables_json | jq -r '
          [to_entries[] | select(.key | IN("scroll", "copy", "search"))
           | .value.entries[] | select(has("rex"))] | length'
      }
      When call stray
      The output should equal "0"
    End

    It 'explains every refusal with a comment'
      # `rex: false` is a decision; the line above it must say why.
      unexplained() {
        awk '/^[[:space:]]*rex: false[[:space:]]*$/ && prev !~ /# rex: / { n++ } { prev = $0 } END { print n + 0 }' \
          home/.chezmoidata/keymap.yaml
      }
      When call unexplained
      The output should equal "0"
    End

    It 'gives a mode switch a destination table that exists'
      dangling() {
        tables_json | jq -r '
          . as $all | to_entries[] | .value.entries[]
          | select(.rex == true) | select((.to // "") as $to | ($all | has($to)) | not) | .desc'
      }
      When call dangling
      The output should equal ""
    End
  End

