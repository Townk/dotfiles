# Tests for the GENERATED Rex config — home/dot_config/rex/init.lua.tmpl,
# rendered from home/.chezmoidata/keymap.yaml.
#
# keymap.yaml is the single source for three consumers now: the tmux key
# tables, the which-key panel, and Rex's bindings. Each leader-table entry
# carries a `rex:` answer beside its tmux `cmd:`; `keymap.direct` lists the
# Cmd chords. What is pinned here:
#
#   * every entry HAS an answer (an action, {action, args}, true for a mode
#     switch, or false with a reason) — a new tmux binding cannot be added
#     without deciding what it means on Rex;
#   * the three mode-stack behaviours the YAML encodes come out as the three
#     binding shapes (switch → enter the mode, sticky → bare action,
#     otherwise → action wrapped in km_do, which leaves the mode);
#   * the file Rex would actually load is valid, and names only actions that
#     exist.
Describe 'generated Rex config'
  setup_all() {
    RK_TMP=$(mktemp -d)
    chezmoi -S "$SHELLSPEC_PROJECT_ROOT" execute-template <home/dot_config/rex/init.lua.tmpl >"$RK_TMP/init.lua" 2>"$RK_TMP/render.err"
    RK_RC=$?
    RK_LUA="$RK_TMP/init.lua"
  }
  cleanup_all() { [ -n "$RK_TMP" ] && rm -rf "$RK_TMP"; }
  BeforeAll setup_all
  AfterAll cleanup_all

  line() { grep -F -- "$1" "$RK_LUA"; }
  tables_json() { yq -o=json '.keymap.tables' home/.chezmoidata/keymap.yaml; }

  It 'renders'
    rendered() { print -r -- "$RK_RC"; cat "$RK_TMP/render.err"; }
    When call rendered
    The output should equal "0"
  End

  It 'carries the marker the backup script looks for'
    When call line 'GENERATED by chezmoi'
    The status should be success
    The output should be present
  End

  Describe 'keymap.yaml answers'
    It 'has a rex: answer on every leader-table entry'
      missing() {
        tables_json | jq -r '
          to_entries[] | select(.key | IN("scroll", "copy", "search") | not)
          | .key as $t | .value.entries[] | select(has("rex") | not) | "\($t): \(.desc)"'
      }
      When call missing
      The output should equal ""
    End

    It 'leaves the native-replaced tables without answers, on purpose'
      # scroll/copy/search are not generated; an answer there would be dead
      # data that looks like a binding.
      stray() {
        tables_json | jq -r '
          [to_entries[] | select(.key | IN("scroll", "copy", "search"))
           | .value.entries[] | select(has("rex"))] | length'
      }
      When call stray
      The output should equal "0"
    End

    It 'explains every refusal with a comment'
      # `rex: false` is a decision; the line above it must say why.
      unexplained() {
        awk '/^[[:space:]]*rex: false[[:space:]]*$/ && prev !~ /# rex: / { n++ } { prev = $0 } END { print n + 0 }' \
          home/.chezmoidata/keymap.yaml
      }
      When call unexplained
      The output should equal "0"
    End

    It 'gives a mode switch a destination table that exists'
      dangling() {
        tables_json | jq -r '
          . as $all | to_entries[] | .value.entries[]
          | select(.rex == true) | select((.to // "") as $to | ($all | has($to)) | not) | .desc'
      }
      When call dangling
      The output should equal ""
    End
  End

  Describe 'binding shapes'
    It 'enters the destination mode for a switch entry'
      When call line 'rex.bind("prefix/t", "client.mode.enter", { name = "tab" })'
      The output should be present
    End

    It 'binds a sticky entry to the bare action, so the mode survives'
      When call line 'rex.bind("pane/h", "pane.focus.left")'
      The output should be present
    End

    It 'wraps a one-shot entry in km_do, so the mode ends'
      When call line 'rex.bind("prefix/z", "km_do", { action = "pane.zoom" })'
      The output should be present
    End

    It 'passes arguments through the wrapper'
      When call line 'rex.bind("tab/0", "km_do", { action = "client.tab.goto", args = { index = 10 } })'
      The output should be present
    End

    It 'binds our own actions directly — they open prompts, which rex.invoke cannot'
      When call line 'rex.bind("session/shift+s", "ql_workspace")'
      The output should be present
    End

    It 'binds every key variant of an entry'
      variants() { grep -c -E '^rex\.bind\("pane/(up|k)", "pane\.focus\.up"\)$' "$RK_LUA"; }
      When call variants
      The output should equal "2"
    End

    It 'emits nothing for a refused entry'
      refused() { grep -c -E '^rex\.bind\("prefix/(shift\+l|u|i|k|f)",' "$RK_LUA" || true; }
      When call refused
      The output should equal "0"
    End

    It 'gives every mode a way out, and every child mode a way back'
      exits() {
        local m
        for m in prefix tab pane resize move session; do
          grep -qF "rex.bind(\"$m/escape\", \"client.mode.exit_all\")" "$RK_LUA" || print -r -- "no escape: $m"
        done
        for m in tab pane resize move session; do
          grep -qF "rex.bind(\"$m/backspace\", \"client.mode.exit\")" "$RK_LUA" || print -r -- "no back: $m"
        done
      }
      When call exits
      The output should equal ""
    End

    It 'declares the leader modes exclusive'
      modes() { grep -c -E '^rex\.mode\("(prefix|tab|pane|resize|move|session)", \{ exclusive = true \}\)$' "$RK_LUA"; }
      When call modes
      The output should equal "6"
    End
  End

  Describe 'key spelling'
    It 'spells an uppercase letter as shift+letter'
      When call line 'rex.bind("prefix/shift+v",'
      The output should be present
    End

    It 'spells tmux modifier prefixes'
      When call line 'rex.bind("prefix/alt+y",'
      The output should be present
    End

    It 'spells the shifted arrows'
      When call line 'rex.bind("pane/shift+up",'
      The output should be present
    End

    It 'spells + as the shifted = it is typed with'
      When call line 'rex.bind("resize/shift+=",'
      The output should be present
    End

    It 'leaves no tmux spelling behind'
      leftovers() { grep -c -E '^rex\.bind\("[a-z]+/([SMC]-|[A-Z])' "$RK_LUA" || true; }
      When call leftovers
      The output should equal "0"
    End

    It 'never binds the same key twice in one mode'
      dupes() { grep -o -E '^rex\.bind\("[^"]+"' "$RK_LUA" | sort | uniq -d; }
      When call dupes
      The output should equal ""
    End

    It 'fails the render on a key name it cannot spell'
      bad_key() {
        sed 's/"Up" "up"/"Upp" "up"/' home/dot_config/rex/init.lua.tmpl |
          chezmoi -S "$SHELLSPEC_PROJECT_ROOT" execute-template 2>&1 >/dev/null || true
      }
      When call bad_key
      The output should include 'no Rex spelling for key'
    End
  End

  Describe 'direct chords'
    It 'binds the three pickers to their Cmd chords'
      pickers() {
        line 'rex.bind("cmd+shift+s", "ql_workspace")'
        line 'rex.bind("cmd+shift+t", "ql_tab")'
        line 'rex.bind("cmd+shift+p", "ql_pane")'
      }
      When call pickers
      The lines of output should equal 3
    End

    It 'maps Cmd+0 to the tenth tab'
      When call line 'rex.bind("cmd+0", "client.tab.goto", { index = 10 })'
      The output should be present
    End

    It 'emits nothing for a refused chord'
      refused() { grep -c -E '^rex\.bind\("cmd\+shift\+(f|v)",' "$RK_LUA" || true; }
      When call refused
      The output should equal "0"
    End
  End

  Describe 'as Rex reads it'
    rex_missing() { ! command -v rex >/dev/null 2>&1; }
    Skip if 'rex is not installed' rex_missing

    It 'passes rex config check'
      When call rex config check "$RK_LUA"
      The status should be success
      The output should include "modes: 6"
      The output should include "actions: 6"
    End

    It 'defines every one of our actions that a binding names'
      undefined() {
        local a
        for a in $(grep -o -E '^rex\.bind\("[^"]+", "[a-z_]+"' "$RK_LUA" | sed -E 's/.*, "//; s/"$//' | sort -u); do
          grep -q "name *= *\"$a\"" "$RK_LUA" || print -r -- "$a"
        done
      }
      When call undefined
      The output should equal ""
    End
  End
End
