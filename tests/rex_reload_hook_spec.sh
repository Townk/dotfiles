# Tests for the two chezmoi hooks that surround ~/.config/rex/init.lua:
#
#   run_before_06-backup-unmanaged-rex-config   keeps ONE copy of the config
#       that existed before chezmoi owned the file;
#   run_onchange_after_59-reload-rex            tells a running server to
#       re-read the file — after checking it, and without ever starting one.
#
# Both are run for real, rendered, against a stub `rex` that logs its argv.
Describe 'Rex config hooks'
  BACKUP_HOOK="$SHELLSPEC_PROJECT_ROOT/home/.chezmoiscripts/run_before_06-backup-unmanaged-rex-config.sh.tmpl"
  RELOAD_HOOK="$SHELLSPEC_PROJECT_ROOT/home/.chezmoiscripts/run_onchange_after_59-reload-rex.sh.tmpl"

  setup() {
    spec_sandbox; RH_TMP=$SANDBOX
    RH_HOME="$RH_TMP/home"
    mkdir -p "$RH_HOME/.config/rex"
    spec_render_template "$BACKUP_HOOK" "$RH_TMP/backup.sh"
    spec_render_template "$RELOAD_HOOK" "$RH_TMP/reload.sh"
    # Fake rex: logs argv; `whoami` answers per $STUB_SERVER; `config check`
    # reads a file, so it answers with no server too, per $STUB_CHECK.
    spec_fake_rex "$RH_TMP" --offline \
      '*" config check "*) [ "${STUB_CHECK:-ok}" = ok ] || { echo "error: syntax error"; exit 1; } ;;'
  }
  BeforeEach 'setup'

  backup() { env HOME="$RH_HOME" XDG_STATE_HOME="$RH_HOME/.local/state" sh "$RH_TMP/backup.sh"; }
  reload() { env HOME="$RH_HOME" MUX_REX_BIN="${1-$RH_TMP/rex}" PATH=/usr/bin:/bin sh "$RH_TMP/reload.sh"; }
  calls() { spec_stub_calls "$RH_TMP" rex; }
  kept() { cat "$RH_HOME/.local/state/rex/init.lua.pre-chezmoi" 2>/dev/null; }

  Describe 'backup'
    It 'keeps a copy of a config chezmoi did not write'
      print -r -- 'rex.bind("x", "pane.zoom") -- mine' >"$RH_HOME/.config/rex/init.lua"
      When call backup
      The output should include "Kept the previous Rex config"
      The contents of file "$RH_HOME/.local/state/rex/init.lua.pre-chezmoi" should include "-- mine"
    End

    It 'does not back up the generated file'
      print -r -- '-- ~/.config/rex/init.lua — GENERATED by chezmoi.' >"$RH_HOME/.config/rex/init.lua"
      When call backup
      The output should equal ""
      The path "$RH_HOME/.local/state/rex/init.lua.pre-chezmoi" should not be exist
    End

    It 'never overwrites the copy it already made'
      twice() {
        print -r -- 'first' >"$RH_HOME/.config/rex/init.lua"
        backup >/dev/null
        print -r -- 'second' >"$RH_HOME/.config/rex/init.lua"
        backup
        kept
      }
      When call twice
      The output should equal "first"
    End

    It 'does nothing when there is no config at all'
      rm -f "$RH_HOME/.config/rex/init.lua"
      When call backup
      The status should be success
      The output should equal ""
    End
  End

  Describe 'reload'
    with_conf() { print -r -- '-- conf' >"$RH_HOME/.config/rex/init.lua"; }

    It 'checks, then reloads, when a server is running'
      with_conf
      When call reload
      The output should include "Reloaded the Rex config"
      The contents of file "$RH_TMP/rex.log" should include "config check"
      The contents of file "$RH_TMP/rex.log" should include "--autostart=false config reload"
    End

    It 'does not reload a config that fails the check'
      with_conf
      STUB_CHECK=bad
      export STUB_CHECK
      When call reload
      The status should be success
      The stderr should include "did not pass"
      The stderr should include "syntax error"
      The contents of file "$RH_TMP/rex.log" should not include "config reload"
    End

    It 'does nothing when no server is running, and never starts one'
      with_conf
      STUB_SERVER=down
      export STUB_SERVER
      quiet() {
        reload
        # every call the hook made must have refused to autostart
        grep -v -e '--autostart=false' -e 'config check' "$RH_TMP/rex.log" | wc -l | tr -d ' '
      }
      When call quiet
      The output should equal "0"
      The contents of file "$RH_TMP/rex.log" should not include "config reload"
    End

    It 'does nothing when the config file is absent'
      When call reload
      The status should be success
      The path "$RH_TMP/rex.log" should not be exist
    End

    It 'does nothing on a machine without rex'
      with_conf
      When call reload ""
      The status should be success
      The output should equal ""
    End

    It 'reloads when either the template or the keymap data changes'
      src() { cat "$RELOAD_HOOK"; }
      When call src
      The output should include 'dot_config/rex/init.lua.tmpl" | sha256sum'
      The output should include '.chezmoidata/keymap.yaml" | sha256sum'
    End
  End
End
