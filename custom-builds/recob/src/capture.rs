    #[test]
    fn previews_flatten_trim_and_truncate_on_codepoint_boundaries() {
        assert_eq!(preview_of("  \n\n  first  \r\n second\n"), "first second");
        // "éa" is 3 bytes, so byte 100 of 40 repeats falls inside the é of the
        // 34th repeat (99 = 33 × 3) and the cut must back off to 99 bytes.
        let long = "éa".repeat(40);
        let flattened = preview_of(&long);
        assert!(flattened.ends_with('…'));
        assert_eq!(flattened.trim_end_matches('…').len(), 99);
    }

