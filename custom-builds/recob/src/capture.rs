    #[test]
    fn the_type_hash_matches_the_lua_construction() {
        // sha256("a=1\nb=2"), the sorted uti=blob set joined by newlines —
        // computed independently to pin the byte layout, since dedup against
        // rows the Lua writer inserted depends on it.
        let mut data = BTreeMap::new();
        data.insert("b".to_string(), b"2".to_vec());
        data.insert("a".to_string(), b"1".to_vec());
        let (hash, total) = type_hash(&data);
        let mut hasher = Sha256::new();
        hasher.update(b"a=1\nb=2");
        let expected: Vec<String> = hasher
            .finalize()
            .iter()
            .map(|byte| format!("{byte:02x}"))
            .collect();
        assert_eq!(hash, expected.concat());
        assert_eq!(total, 2);
    }

